import { z } from 'zod';

/** POST /api/user/login */
export const loginSchema = z.object({
	email: z.string().email(),
	password: z.string().min(1),
	stayLoggedIn: z.boolean().optional()
});

/**
 * POST /api/user/register — creates a new account only.
 * Unknown keys (e.g. a client-supplied userId/_id) are stripped by validate(), so a request
 * can never target an existing account through registration.
 */
export const registerSchema = z.object({
	email: z.string().email(),
	password: z.string().min(8, 'Password must be at least 8 characters')
});

/** POST /api/user/resetpassword */
export const forgotPasswordSchema = z.object({
	email: z.string().email()
});

/** PATCH /api/user/reset */
export const resetPasswordSchema = z.object({
	uuid: z.string().uuid(),
	password: z.string().min(8, 'Password must be at least 8 characters')
});

/** POST /api/user/mergeGithub — merge-token-based approach.
 *
 * The userId is no longer accepted here (it was a client-controlled account-takeover vector).
 * Instead, mergeToken is an opaque, single-use token generated by initiateMergeGithub for the session's own account.
 * The server resolves the target account from the stored token, proving ownership without trusting any
 * client-supplied account identifier.
 */
export const mergeGithubSchema = z.object({
	mergeToken: z.string().min(1, 'mergeToken is required')
});

/**
 * POST /api/user/mergeGithub/initiate — the target Seed account to merge a GitHub identity into.
 * The session check in the controller is the actual ownership proof; this schema only
 * rejects malformed or operator-shaped input before it reaches the handler.
 */
export const initiateMergeGithubSchema = z.object({
	userId: z.string().regex(/^[0-9a-f]{24}$/i, 'userId must be a valid ObjectId')
});

/**
 * POST /api/user/update/:userID — change-password-while-logged-in flow.
 * Requires the current password (verified against the stored hash) before a new
 * one is applied. Unknown keys (e.g. email) are rejected with a 400 by .strict().
 */
export const updateUserSchema = z
	.object({
		currentPassword: z.string().min(8, 'Current password must be at least 8 characters'),
		newPassword: z.string().min(8, 'Password must be at least 8 characters')
	})
	// Strict: reject unknown keys (e.g. email) instead of silently stripping them —
	// sensitive fields may only come from the session user, not the request body
	.strict();

